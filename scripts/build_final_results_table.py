"""Single source of truth for the final numbers.

Collects the validated results produced by experiment_clean_validation.py,
experiment_quadrant_analysis.py and experiment_vs_original_da1.py into
comparison/final_results.json and a human-readable comparison/final_results.md.
RESULTS.md and the paper are written from this file, so there is exactly one
place where a number can be wrong.

Feature-source policy (see README "Decoding-time contamination"):
  Qwen2.5-1.5B-Instruct  -> clean features (generate() scores were distorted by
                            repetition_penalty = 1.1 in its generation_config)
  Llama-3.2-1B / SmolLM2 -> original features (no penalty configured; recomputing
                            from raw logits shifts mean log-probability by <= 0.006,
                            and Llama's greedy decoding does not reproduce exactly
                            for long answers, so its clean subset is length-biased)

Usage:
    python scripts/build_final_results_table.py
"""
import json
from pathlib import Path

import pandas as pd
from scipy import stats
from sklearn.metrics import cohen_kappa_score

ROOT = Path(__file__).resolve().parent.parent
MODELS = [("qwen2.5-1.5b-instruct", "Qwen2.5-1.5B", "clean"),
          ("llama-3.2-1b-instruct", "Llama-3.2-1B", "rich"),
          ("smollm2-1.7b-instruct", "SmolLM2-1.7B", "rich")]
DATASETS = [("truthfulqa", "TruthfulQA"), ("sciq", "SciQ")]
KEY_DETECTORS = ["flat__original_3feat", "flat__all_17feat", "flat__all_16feat_no_length",
                 "cascade__all_17feat", "cascade__candidate_4feat", "flat__candidate_4feat"]


def load(path):
    p = ROOT / path
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main():
    out = {"feature_source_policy": {m: f for m, _, f in MODELS}, "cells": {}}
    md = ["# Final validated results",
          "",
          "Generated by `scripts/build_final_results_table.py` from saved experiment outputs.",
          "Qwen uses decontaminated features; Llama/SmolLM2 use their original (uncontaminated) features.",
          "`p` is a permutation-test p-value (500 label shuffles, 5-fold OOF re-run each time).",
          "`repCV` is the mean +/- sd of 5-fold OOF AUROC over 20 different CV seeds.",
          ""]

    # ---- dataset / labeler characteristics ----
    md += ["## Dataset and labeler characteristics", "",
           "| Model | Dataset | n | Halluc. rate (token-F1) | Halluc. rate (embedding) | Agreement | kappa | Length bias p (token-F1) |",
           "|---|---|---|---|---|---|---|---|"]
    for key, disp, src in MODELS:
        for ds, dsd in DATASETS:
            f = ROOT / f"results/{key}/{ds}/features"
            rich = pd.read_csv(f / f"single_pass_features_{src}.csv")
            sem = pd.read_csv(f / "single_pass_features_semantic_labels.csv")[["qid", "semantic_label"]]
            d = rich.merge(sem, on="qid")
            g, h = d[d.label == 0]["answer_length"], d[d.label == 1]["answer_length"]
            _, p_len = stats.ttest_ind(g, h)
            agree = float((d.label == d.semantic_label).mean())
            kappa = float(cohen_kappa_score(d.label, d.semantic_label))
            out["cells"].setdefault(f"{key}|{ds}", {})["characteristics"] = {
                "n": len(d), "halluc_rate_tokenf1": float(d.label.mean()),
                "halluc_rate_embedding": float(d.semantic_label.mean()),
                "labeler_agreement": agree, "cohen_kappa": kappa, "length_bias_p_tokenf1": float(p_len)}
            md.append(f"| {disp} | {dsd} | {len(d)} | {d.label.mean():.2f} | {d.semantic_label.mean():.2f} | "
                      f"{agree:.3f} | {kappa:.3f} | {p_len:.3f} |")

    # ---- confidently-wrong ----
    md += ["", "## Confidently wrong (share of wrong answers with above-median mean log-probability)", "",
           "| Model | TruthfulQA | SciQ |", "|---|---|---|"]
    for key, disp, src in MODELS:
        row = []
        for ds, _ in DATASETS:
            q = load(f"results/{key}/{ds}/analysis/quadrant_analysis_{src}.json") or \
                load(f"results/{key}/{ds}/analysis/quadrant_analysis.json")
            c = q["quadrant_counts"]
            wc, wu = c["wrong_confident"]["n"], c["wrong_uncertain"]["n"]
            frac = 100 * wc / (wc + wu)
            out["cells"][f"{key}|{ds}"]["confidently_wrong_pct"] = frac
            row.append(f"{frac:.1f}%")
        md.append(f"| {disp} | {row[0]} | {row[1]} |")

    # ---- detector results ----
    for labels, lab_disp in [("tokenf1", "token-F1 labels"), ("semantic", "embedding labels")]:
        md += ["", f"## Detector performance, 5-fold OOF ({lab_disp})", "",
               "| Model | Dataset | Detector | AUROC | 95% CI | repCV | perm p |", "|---|---|---|---|---|---|---|"]
        for key, disp, src in MODELS:
            for ds, dsd in DATASETS:
                suffix = "_semlabels" if labels == "semantic" else ""
                v = load(f"results/{key}/{ds}/analysis/clean_validation_{src}{suffix}.json")
                if not v:
                    continue
                for det in KEY_DETECTORS:
                    r = v["detectors"].get(det)
                    if not r:
                        continue
                    out["cells"][f"{key}|{ds}"].setdefault(f"detectors_{labels}", {})[det] = r
                    star = "*" if r["permutation_p_value"] < 0.05 else ""
                    md.append(f"| {disp} | {dsd} | {det} | {r['auroc_reference_seed']:.3f}{star} | "
                              f"[{r['bootstrap_ci'][0]:.3f}, {r['bootstrap_ci'][1]:.3f}] | "
                              f"{r['repeated_cv_mean']:.3f}±{r['repeated_cv_std']:.3f} | "
                              f"{r['permutation_p_value']:.3f} |")

    # ---- fixed 60-question holdout ----
    md += ["", "## Fixed 60-question holdout (the original DA1 evaluation split), TruthfulQA", "",
           "| Model | Detector | AUROC | 95% CI |", "|---|---|---|---|"]
    for key, disp, src in MODELS:
        v = load(f"results/{key}/truthfulqa/analysis/vs_original_da1_same_split_{src}.json") or \
            load(f"results/{key}/truthfulqa/analysis/vs_original_da1_same_split.json")
        if not v:
            continue
        out["cells"][f"{key}|truthfulqa"]["fixed_holdout"] = v
        for det, r in v.items():
            md.append(f"| {disp} | {det} | {r['point_estimate']:.3f} | "
                      f"[{r['ci_lower_2.5pct']:.3f}, {r['ci_upper_97.5pct']:.3f}] |")

    (ROOT / "comparison" / "final_results.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    (ROOT / "comparison" / "final_results.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("Wrote comparison/final_results.json and comparison/final_results.md")
    print("\n".join(md[:40]))


if __name__ == "__main__":
    main()
